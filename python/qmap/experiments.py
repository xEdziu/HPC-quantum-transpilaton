"""Experiment pipeline: run-script generation, pilot targets, aggregation, validation and plots.

Directory layout of one run (created by the generated PowerShell script):
    <out>/<config>/<instance>/<tag>/rep<k>/{summary.json,run_r<rank>.csv,best.qasm,best.json,stdout.txt}
where <tag> is eps<e> (target from the pilot table) or target<N> (explicit target).
Definitions: docs/adr/0010-ttt.md; procedure: docs/protokol-eksperymentow.md.
"""
import argparse
import csv
import json
import math
from pathlib import Path, PureWindowsPath

import numpy as np
import pandas as pd

DEFAULT_CONFIGS = ["rtx5080", "rtx5080+rtx3060", "rtx5080+rtx5070", "rtx5080+rtx5070+rtx3060"]
DEFAULT_EPS = [0.10, 0.05, 0.02]


def load_cluster(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def eps_tag(eps):
    return f"eps{eps:.2f}"


def target_for(best_known, eps):
    # round() first: (1 + 0.1) * 10 is 11.000000000000002 in floating point, and ceil would give 12.
    return math.ceil(round((1 + eps) * best_known, 9))


def read_targets(path):
    """targets.csv -> {(instance, tag): target}"""
    with open(path, encoding="utf-8", newline="") as f:
        return {(r["instance"], eps_tag(float(r["eps"]))): int(r["target"]) for r in csv.DictReader(f)}


def rank_command(cluster, host, instance, target, seed, max_time, migration, topology, run_dir, rank0):
    """One mpiexec section (-n 1 -host H exe args) for a single rank."""
    args = [
        f"-n 1 -host {host['host']} {cluster['exe']}",
        f"--instance data\\instances\\{instance}.qasm", f"--device {cluster['device']}",
        f"--pop {host['pop']}", f"--max-time {max_time:g}", f"--target {target}", f"--seed {seed}",
        f"--migration {migration}", f"--topology {topology}", f"--log {run_dir}\\run.csv",
    ]
    if rank0:
        args += [f"--summary {run_dir}\\summary.json", f"--out-qasm {run_dir}\\best.qasm",
                 f"--out-layout {run_dir}\\best.json"]
    return " ".join(args)


def build_script(cluster, instances, configs, targets, reps, max_time, migration, topology, out):
    """PowerShell script text (ASCII only); targets = {(instance, tag): target}."""
    hosts = {h["name"]: h for h in cluster["hosts"]}
    # -genv (not -env): in MPMD form -env applies only to the first section. MPICH_NETMASK keeps MS-MPI
    # off virtual adapters (Hyper-V, VirtualBox) and Wi-Fi that other hosts cannot reach.
    genv = f" -genv MPICH_NETMASK {cluster['netmask']}" if cluster.get("netmask") else ""
    lines = [
        "# Generated by: python -m qmap.experiments plan. Run on the rank-0 host from PowerShell.",
        "# Resumable: runs whose summary.json exists are skipped.",
        f"Set-Location '{cluster['repo_path']}'",
        "",
    ]
    # rep is the outermost loop so that configs interleave in time (thermal drift does not favour one config);
    # seed = rep: identical across configs (paired comparison).
    for rep in range(1, reps + 1):
        for instance in instances:
            for (inst, tag), target in sorted(targets.items()):
                if inst != instance:
                    continue
                for config in configs:
                    members = [hosts[n] for n in config.split("+")]
                    run_dir = f"{out}\\{config}\\{instance}\\{tag}\\rep{rep}"
                    ranks = [rank_command(cluster, h, instance, target, rep, max_time, migration, topology,
                                          run_dir, i == 0) for i, h in enumerate(members)]
                    lines.append(f"if (-not (Test-Path {run_dir}\\summary.json)) {{")
                    # local dir for Tee-Object; qmap_ga creates the run dir on remote hosts itself
                    lines.append(f"    New-Item -ItemType Directory -Force {run_dir} | Out-Null")
                    lines.append(f"    mpiexec{genv} {' : '.join(ranks)} | Tee-Object {run_dir}\\stdout.txt")
                    lines.append("}")
    return "\n".join(lines) + "\n"


def cmd_plan(a):
    cluster = load_cluster(a.cluster)
    if a.targets_from:
        targets = read_targets(a.targets_from)
        instances = a.instances or sorted({i for i, _ in targets})
    else:
        if a.target is None or not a.instances:
            raise SystemExit("plan: give --targets-from, or both --instances and --target")
        instances = a.instances
        targets = {(i, f"target{a.target}"): a.target for i in instances}
    text = build_script(cluster, instances, a.configs, targets, a.reps, a.max_time, a.migration, a.topology,
                        a.out.replace("/", "\\"))
    path = Path(a.script)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="ascii", newline="\n") as f:  # raises on non-ASCII
        f.write(text)
    print(f"wrote {path} ({text.count('Tee-Object')} runs)")


def instance_name(path):
    return PureWindowsPath(path).stem  # handles both "/" and "\" separators


def compute_targets(summaries, eps_list):
    """summaries: iterable of summary dicts -> rows (instance, B, eps, target); B = min best per instance."""
    best = {}
    for s in summaries:
        name = instance_name(s["instance"])
        best[name] = min(best.get(name, s["best"]), s["best"])
    return [{"instance": n, "B": b, "eps": f"{e:.2f}", "target": target_for(b, e)}
            for n, b in sorted(best.items()) for e in eps_list]


def cmd_pilot(a):
    summaries = [json.loads(p.read_text(encoding="utf-8")) for p in Path(a.runs).rglob("summary.json")]
    if not summaries:
        raise SystemExit(f"pilot: no summary.json under {a.runs}")
    rows = compute_targets(summaries, a.eps)
    path = Path(a.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, ["instance", "B", "eps", "target"], lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    for r in rows:
        print(r)


def load_runs(runs_dir):
    """One row per run (summary.json); throughput = sum over ranks of mean evals_per_s, if all rank CSVs exist."""
    rows = []
    for sp in sorted(Path(runs_dir).rglob("summary.json")):
        rel = sp.parent.relative_to(runs_dir).parts
        if len(rel) != 4:
            continue
        s = json.loads(sp.read_text(encoding="utf-8"))
        csvs = sorted(sp.parent.glob("run_r*.csv"))
        thr = sum(pd.read_csv(c)["evals_per_s"].mean() for c in csvs) if len(csvs) == s["n_ranks"] else math.nan
        vp = sp.parent / "validate.json"
        rows.append({
            "config": rel[0], "instance": rel[1], "eps": rel[2], "rep": int(rel[3][3:]), "dir": str(sp.parent),
            "best": s["best"], "target": s["target"], "n_ranks": s["n_ranks"],
            "ttt_s": math.nan if s["ttt_s"] is None else s["ttt_s"], "throughput": thr,
            "valid": json.loads(vp.read_text(encoding="utf-8"))["valid"] if vp.exists() else None,
        })
    return pd.DataFrame(rows)


def censored_median(ttts, n):
    """Lower median of n runs where the runs missing from ttts are censored (+inf); NaN if undefined."""
    k = math.ceil(n / 2)
    s = sorted(ttts)
    return s[k - 1] if k <= len(s) else math.nan


def aggregate_runs(df, baseline="rtx5080"):
    """Per (config, instance, eps): success rate, censored median TTT, IQR of successes, speedup, efficiency."""
    rows = []
    for (config, instance, eps), g in df.groupby(["config", "instance", "eps"]):
        ok = g["ttt_s"].dropna().to_numpy()
        checked = [v for v in g["valid"] if v is not None]
        rows.append({
            "config": config, "instance": instance, "eps": eps, "target": g["target"].iloc[0], "n": len(g),
            "successes": len(ok), "success_rate": len(ok) / len(g),
            "median_ttt_s": censored_median(ok, len(g)),
            "q1_ttt_s": float(np.percentile(ok, 25)) if len(ok) else math.nan,
            "q3_ttt_s": float(np.percentile(ok, 75)) if len(ok) else math.nan,
            "best_min": int(g["best"].min()), "throughput": g["throughput"].mean(),
            "validated": len(checked), "valid": sum(bool(v) for v in checked),
        })
    out = pd.DataFrame(rows)
    base = out[out["config"] == baseline].set_index(["instance", "eps"])
    key = list(zip(out["instance"], out["eps"]))
    b_ttt = pd.Series([base["median_ttt_s"].get(k, math.nan) for k in key], index=out.index)
    b_thr = pd.Series([base["throughput"].get(k, math.nan) for k in key], index=out.index)
    out["speedup"] = b_ttt / out["median_ttt_s"]
    out["efficiency"] = out["speedup"] / (out["throughput"] / b_thr)  # Alba: speedup / relative compute capacity
    return out


def quality_table(df, sabre_csv):
    """Best GA SWAP per instance (min over all runs) vs SABRE min / median."""
    sabre = pd.read_csv(sabre_csv).groupby("instance")["swaps"].agg(sabre_min="min", sabre_median="median")
    ga = df.groupby("instance")["best"].min().rename("ga_best")
    out = pd.concat([ga, sabre], axis=1, join="inner").reset_index()
    out["ga_over_sabre_min"] = out["ga_best"] / out["sabre_min"]
    return out


def cmd_aggregate(a):
    df = load_runs(a.runs)
    if df.empty:
        raise SystemExit(f"aggregate: no runs under {a.runs}")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    agg = aggregate_runs(df, a.baseline_config)
    agg.to_csv(out / "aggregate.csv", index=False, lineterminator="\n")
    print(agg.to_string(index=False))
    if Path(a.sabre).exists():
        q = quality_table(df, a.sabre)
        q.to_csv(out / "quality.csv", index=False, lineterminator="\n")
        print(q.to_string(index=False))


def cmd_validate_runs(a):
    from qmap.device import load_device
    from qmap.instances import load_instance, loads
    from qmap.validate import validate

    _, cm = load_device()
    for sp in sorted(Path(a.runs).rglob("best.json")):
        if (sp.parent / "validate.json").exists() or not (sp.parent / "best.qasm").exists():
            continue
        instance = sp.parent.parent.parent.name
        layout = json.loads(sp.read_text(encoding="utf-8"))
        routed = loads((sp.parent / "best.qasm").read_text(encoding="utf-8"))
        report = validate(load_instance(instance), routed, layout["initial"], layout["final"], cm, k=1)
        (sp.parent / "validate.json").write_text(json.dumps(
            {"valid": bool(report["valid"]), "swaps": report["swaps"]}) + "\n", encoding="utf-8")
        print(sp.parent, "valid" if report["valid"] else "INVALID")


def cmd_plot(a):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    df = load_runs(a.runs)
    for (instance, eps), g in df.groupby(["instance", "eps"]):  # ECDF; censored runs keep the curve below 1
        fig, ax = plt.subplots()
        for config, c in g.groupby("config"):
            t = np.sort(c["ttt_s"].dropna().to_numpy())
            ax.step(t, np.arange(1, len(t) + 1) / len(c), where="post", label=f"{config} (n={len(c)})")
        ax.set(xlabel="TTT [s]", ylabel="fraction of runs reaching target", ylim=(0, 1.02),
               title=f"{instance}, {eps}, target {g['target'].iloc[0]}")
        ax.legend()
        fig.savefig(out / f"ttt_ecdf_{instance}_{eps}.png", dpi=150, bbox_inches="tight")
        plt.close(fig)
    if a.convergence:
        run = Path(a.convergence)
        fig, ax = plt.subplots()
        for c in sorted(run.glob("run_r*.csv")):
            d = pd.read_csv(c)
            ax.step(d["elapsed_s"], d["best"], where="post", label=c.stem.split("_")[-1])
        ax.set(xlabel="elapsed [s]", ylabel="best SWAP", title=f"convergence: {'/'.join(run.parts[-4:])}")
        ax.legend()
        fig.savefig(out / f"convergence_{'_'.join(run.parts[-4:])}.png", dpi=150, bbox_inches="tight")
        plt.close(fig)


def build_parser():
    ap = argparse.ArgumentParser(prog="qmap.experiments", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("plan", help="emit a PowerShell script with one mpiexec command per run")
    p.add_argument("--cluster", default="data/cluster.json")
    p.add_argument("--instances", nargs="+")
    p.add_argument("--configs", nargs="+", default=DEFAULT_CONFIGS, help="host names joined by '+'")
    p.add_argument("--targets-from", help="targets.csv from the pilot subcommand")
    p.add_argument("--target", type=int, help="explicit target (pilot: -1 = run until --max-time)")
    p.add_argument("--reps", type=int, default=10)
    p.add_argument("--max-time", type=float, default=120)
    p.add_argument("--migration", default="adaptiveB")
    p.add_argument("--topology", default="all")
    p.add_argument("--out", default="results/runs")
    p.add_argument("--script", default="run_all.ps1")
    p.set_defaults(func=cmd_plan)

    p = sub.add_parser("pilot", help="best-known B per instance from pilot summaries -> targets.csv")
    p.add_argument("--runs", default="results/pilot")
    p.add_argument("--eps", nargs="+", type=float, default=DEFAULT_EPS)
    p.add_argument("--out", default="results/pilot/targets.csv")
    p.set_defaults(func=cmd_pilot)

    p = sub.add_parser("aggregate", help="results/aggregate.csv (TTT, speedup, efficiency) and quality.csv")
    p.add_argument("--runs", default="results/runs")
    p.add_argument("--sabre", default="results/baseline/sabre.csv")
    p.add_argument("--out", default="results")
    p.add_argument("--baseline-config", default="rtx5080")
    p.set_defaults(func=cmd_aggregate)

    p = sub.add_parser("validate-runs", help="run qmap.validate (k=1) on every best.qasm; writes validate.json")
    p.add_argument("--runs", default="results/runs")
    p.set_defaults(func=cmd_validate_runs)

    p = sub.add_parser("plot", help="TTT ECDF per (instance, eps); optional convergence of one run directory")
    p.add_argument("--runs", default="results/runs")
    p.add_argument("--out", default="results/plots")
    p.add_argument("--convergence", help="run directory, e.g. results/runs/rtx5080/qft_n12/eps0.10/rep1")
    p.set_defaults(func=cmd_plot)
    return ap


def main(argv=None):
    a = build_parser().parse_args(argv)
    a.func(a)


if __name__ == "__main__":
    main()
